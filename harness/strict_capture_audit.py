#!/usr/bin/env python3
"""Read-only, fail-closed event-level sanity audit for TRACER 2.0 JSA revision.

Works on CSVs generated by harness/candump2csv.py and bin/ids_runner.
This is an *independent diagnostic*, not a replacement for a validated scorer.
It assumes the fixed phase structure used by scenarios.build_session(live=True)
and requires the original scripted attack order. It does not prove that the
captured traffic originated from the robot, online IDS latency, or physical DoS.

Run:
    python3 TRACER_strict_capture_audit.py --frames results/live_frames.csv \\
      --alerts results/live_frames_al.csv --n 30 --out results/strict_audit.json
"""
import argparse
import collections
import csv
import hashlib
import json
import pathlib
import sys

ATTACK_ORDER = ('A1', 'A2', 'A4', 'A5', 'A6', 'A7', 'A8', 'A9')
HOST_IDS = {0x111, 0x112, 0x121, 0x421, 0x441, 0x666}
ACCEPT = {
    'A1': {'NO_AUTH'}, 'A2': {'NO_AUTH'}, 'A4': {'FLOOD'},
    'A5': {'STALE_SEQ'}, 'A6': {'BAD_MAC', 'BRUTE_FORCE'},
    'A7': {'VEL_JUMP'}, 'A8': {'BAD_MAC', 'BRUTE_FORCE'},
    'A9': {'UNKNOWN_ID'},
}
GRACE_US = 60_000


def load_frames(path):
    out = []
    with open(path, newline='', encoding='utf-8') as f:
        rd = csv.DictReader(f)
        required = {'ts_us', 'can_id', 'dlc', 'data_hex'}
        if not required.issubset(rd.fieldnames or ()):
            raise ValueError('frames CSV missing columns ' + str(required))
        for lineno, row in enumerate(rd, 2):
            try:
                ts = int(row['ts_us'])
                cid = int(row['can_id'], 16)
                dlc = int(row['dlc'])
                data = bytes.fromhex(row['data_hex'])
                if ts < 0 or dlc not in range(9) or len(data) != dlc:
                    raise ValueError('negative time / invalid DLC / payload length')
                out.append((ts, cid, data))
            except (ValueError, TypeError) as ex:
                raise ValueError(f'frame line {lineno}: {ex}') from ex
    if not out or any(out[i][0] < out[i - 1][0] for i in range(1, len(out))):
        raise ValueError('empty or out-of-order frames')
    return out


def load_alerts(path):
    out = []
    with open(path, newline='', encoding='utf-8') as f:
        rd = csv.DictReader(f)
        if not {'timestamp_us', 'alert_type'}.issubset(rd.fieldnames or ()):
            raise ValueError('alerts CSV missing timestamp_us,alert_type')
        for lineno, row in enumerate(rd, 2):
            if not row['timestamp_us'] or row['timestamp_us'].startswith('#'):
                continue
            try:
                out.append((int(row['timestamp_us']), row['alert_type']))
            except (ValueError, TypeError) as ex:
                raise ValueError(f'alert line {lineno}: {ex}') from ex
    return sorted(out)


def phase_groups(hosts, gap_us=1_500_000):
    groups = []
    for fr in hosts:
        if not groups or fr[0] - groups[-1][-1][0] > gap_us:
            groups.append([])
        groups[-1].append(fr)
    return groups


def issue(msgs, ok, text):
    if not ok:
        msgs.append(text)


def split_pairs(rows, msgs, name):
    issue(msgs, len(rows) % 2 == 0, f'{name}: odd frame count')
    pairs = []
    for j in range(0, len(rows) - 1, 2):
        x, y = rows[j], rows[j + 1]
        issue(msgs, x[1] in (0x111, 0x421, 0x441) and y[1] == 0x112,
              f'{name}: frame pair {j//2 + 1} is not CMD -> AUTH')
        issue(msgs, 0 <= y[0] - x[0] <= 8_000,
              f'{name}: pair {j//2 + 1} has invalid companion timing')
        pairs.append((x, y))
    return pairs


def get_events(kind, rows, n, issues, baseline):
    """Return event (start,end) windows; record frame-shape violations separately."""
    issue(issues, bool(rows), f'{kind}: empty attack phase')
    if not rows:
        return []
    if kind in ('A1', 'A2', 'A9'):
        want = {'A1': 0x111, 'A2': 0x421, 'A9': 0x666}[kind]
        issue(issues, len(rows) == n, f'{kind}: expected {n} frames, captured {len(rows)}')
        for idx, (_, cid, _) in enumerate(rows):
            issue(issues, cid == want, f'{kind}: unexpected ID at event {idx+1}')
        return [(t, t) for t, cid, d in rows if cid == want]
    if kind == 'A4':
        issue(issues, len(rows) == 5000,
              f'A4: expected 5000 host flood frames, captured {len(rows)}')
        issue(issues, all(cid == 0x111 and data == bytes(8) for _, cid, data in rows),
              'A4: unexpected frame ID/payload in flood phase')
        duration = (rows[-1][0]-rows[0][0])/1e6
        issue(issues, 4.8 <= duration <= 5.2,
              f'A4: flood duration {duration:.3f}s not approximately 5s')
        return [(rows[0][0], rows[-1][0])]
    if kind == 'A5':
        pairs = split_pairs(rows, issues, kind)
        issue(issues, len(pairs) >= n,
              f'A5: captured fewer than {n} total command/companion pairs')
        if len(pairs) < n:
            return []
        lead, replay = pairs[:-n], pairs[-n:]
        issue(issues, len(lead) == 100,
              f'A5: expected 100 legitimate lead-in pairs, observed {len(lead)}')
        seqs = [int.from_bytes(p[1][2][4:6], 'big') for p in replay if len(p[1][2]) >= 6]
        issue(issues, len(seqs) == n and all(s == 2 for s in seqs),
              'A5: replay companions not all stale seq=2')
        # Can the command and companion be shown byte-for-byte identical to a
        # previously observed pair in the capture? This is a separate semantic claim.
        candidates = split_pairs(baseline, [], 'baseline')
        previous = [(x, y) for x, y in candidates
                    if y[1] == 0x112 and len(y[2]) >= 6
                    and int.from_bytes(y[2][4:6], 'big') == 2]
        if previous:
            refx, refy = previous[0]
            if not all(x[1:] == refx[1:] and y[1:] == refy[1:] for x, y in replay):
                issues.append('A5: NOT a byte-for-byte replay of earlier seq=2 capture')
        else:
            issues.append('A5: earlier seq=2 source pair could not be established')
        return [(x[0], y[0]) for x, y in replay]
    if kind == 'A6':
        pairs = split_pairs(rows, issues, kind)
        issue(issues, len(pairs) == n, f'A6: expected {n} CMD/AUTH pairs, got {len(pairs)}')
        issue(issues, all(x[1] == 0x111 and y[2][:4] == bytes.fromhex('DEADBEEF')
                          for x, y in pairs), 'A6: forged-pair payload differs from scenario')
        return [(x[0], y[0]) for x, y in pairs]
    if kind in ('A7', 'A8'):
        group_size = 4 if kind == 'A7' else 16
        issue(issues, len(rows) == n * group_size,
              f'{kind}: expected {n*group_size} host frames, captured {len(rows)}')
        issue(issues, len(rows) % group_size == 0,
              f'{kind}: partial event/frame loss (group size {group_size})')
        events = []
        for idx in range(0, len(rows) - group_size + 1, group_size):
            block = rows[idx:idx+group_size]
            pairs = split_pairs(block, issues, f'{kind}/event-{idx//group_size+1}')
            if kind == 'A7':
                vals = [int.from_bytes(x[2][:2], 'big') for x, _ in pairs]
                issue(issues, vals == [100, 1800],
                      f'A7/event-{idx//group_size+1}: expected 100->1800, got {vals}')
                # The high-velocity frame is the specific trigger for event attribution.
                events.append((pairs[-1][0][0], pairs[-1][1][0]))
            else:
                issue(issues, all(x[1] == 0x111 for x, y in pairs),
                      f'A8/event-{idx//group_size+1}: unexpected command ID')
                events.append((block[0][0], block[-1][0]))
        return events
    raise ValueError('unknown attack ' + kind)


def audit(frames_path, alerts_path, n):
    frames = load_frames(frames_path)
    alerts = load_alerts(alerts_path)
    hosts = [row for row in frames if row[1] in HOST_IDS]
    phases = phase_groups(hosts)
    issues = []
    issue(issues, len(phases) == 10,
          f'expected 10 phases (2 baseline + 8 attacks), captured {len(phases)}')
    if len(phases) != 10:
        return dict(status='FAIL', issues=issues, phase_count=len(phases), attacks={})
    baseline = phases[0] # first signed baseline (contains seq=2)
    entries = {}
    all_attack_windows = []
    for kind, rows in zip(ATTACK_ORDER, phases[2:]):
        shape_errors = []
        events = get_events(kind, rows, n, shape_errors, baseline)
        expected = 1 if kind == 'A4' else n
        issue(shape_errors, len(events) == expected,
              f'{kind}: reconstructed {len(events)}/{expected} events')
        # Ensure events do not overlap once bounded alert-matching grace is used.
        windows = [(x-GRACE_US, y+GRACE_US) for x,y in events]
        issue(shape_errors, all(windows[i][1] < windows[i+1][0]
                                for i in range(len(windows)-1)),
              f'{kind}: overlapping event windows; alert assignment ambiguous')
        used = set()
        rows_evidence = []
        for idx, (x, y) in enumerate(events, 1):
            matches = [(j,ts,ty) for j,(ts,ty) in enumerate(alerts)
                       if j not in used and ty in ACCEPT[kind]
                       and x-GRACE_US <= ts <= y+GRACE_US]
            if matches:
                j,ts,ty=matches[0]; used.add(j)
                match = {'timestamp_us': ts, 'alert_type': ty}
            else:
                match = None
            rows_evidence.append({'event': idx, 't0_us':x, 't1_us':y,
                                  'matched_alert':match})
        detected=sum(e['matched_alert'] is not None for e in rows_evidence)
        entries[kind] = {'expected':expected,'reconstructed':len(events),
                         'detected':detected,'all_expected_events_detected':detected==expected,
                         'frame_shape_errors':shape_errors, 'events':rows_evidence,
                         'captured_host_frames':len(rows)}
        all_attack_windows.append((rows[0][0]-200_000, rows[-1][0]+200_000))
        issues.extend(shape_errors)
    def inside_attack(ts):
        return any(a<=ts<=b for a,b in all_attack_windows)
    fp = [ty for ts,ty in alerts if not inside_attack(ts)]
    nben = sum(1 for ts,c,d in frames if not inside_attack(ts))
    return {
        'status':'PASS' if not issues and all(v['all_expected_events_detected'] for v in entries.values()) else 'FAIL',
        'meaning':'scripted-capture structural check; not proof of online detection, real DoS, or external generalization',
        'frames_sha256':hashlib.sha256(pathlib.Path(frames_path).read_bytes()).hexdigest(),
        'alerts_sha256':hashlib.sha256(pathlib.Path(alerts_path).read_bytes()).hexdigest(),
        'total_captured_frames':len(frames),
        'phase_count':len(phases), 'expected_trial_count':n,
        'issues':issues, 'attacks':entries,
        'benign':{'frames_outside_attack_windows':nben,
                  'alerts_outside_attack_windows':len(fp),
                  'alerts_by_rule':dict(collections.Counter(fp))}
    }


def main():
    pa=argparse.ArgumentParser(description=__doc__)
    pa.add_argument('--frames', required=True)
    pa.add_argument('--alerts', required=True)
    pa.add_argument('--n', type=int, default=30)
    pa.add_argument('--out', required=True)
    args=pa.parse_args()
    if args.n <= 0:
        pa.error('--n must be positive')
    try:
        report=audit(args.frames,args.alerts,args.n)
    except (ValueError,OSError) as ex:
        print('AUDIT FAILED:',ex,file=sys.stderr)
        return 2
    with open(args.out,'w',encoding='utf-8') as fp:
        json.dump(report,fp,indent=2,ensure_ascii=False)
    print('STRICT EVIDENCE AUDIT:',report['status'])
    print('  capture phases:',report.get('phase_count'))
    for kind,row in report['attacks'].items():
        print(' ',kind, f"{row['detected']}/{row['expected']} matched",
              f"{row['reconstructed']} reconstructed",
              'SHAPE_OK' if not row['frame_shape_errors'] else 'SHAPE_FAIL')
    for issue_text in report['issues']:
        print('  ISSUE:',issue_text)
    print('  output:',args.out)
    return 0 if report['status']=='PASS' else 1

if __name__ == '__main__':
    raise SystemExit(main())
