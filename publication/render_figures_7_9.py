#!/usr/bin/env python3
"""Create manuscript Figs 7--9 directly from the preserved source outputs.

Fig. 7 reads results/sweeps.json, which is generated by `python harness/sweep.py`.
Fig. 8 reads results/validated_threshold_diagnostics.json, generated by
`python harness/sweep_validated.py`.
Fig. 9 reads results/today_final_audit/hmac_ubuntu_200k.json, which is a
preserved *summary* of an earlier Ubuntu-host microbenchmark, not raw times.
The summary cannot reconstruct the original per-invocation distribution.

No statistic is hardcoded. Captions should characterize Figs. 7--8 as synthetic
software diagnostics and Fig. 9 as host-only cryptographic measurements.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import ListedColormap

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'publication' / 'figures'
plt.rcParams.update({
    'font.family': 'DejaVu Sans', 'font.size': 14, 'axes.titlesize': 16,
    'axes.titleweight': 'bold', 'axes.labelsize': 14,
    'xtick.labelsize': 12, 'ytick.labelsize': 12,
    'figure.facecolor': 'white', 'axes.facecolor': 'white',
    'savefig.facecolor': 'white', 'pdf.fonttype': 42, 'ps.fonttype': 42,
})


def read_json(path: Path):
    if not path.is_file():
        raise FileNotFoundError(f'Required preserved input missing: {path}')
    return json.loads(path.read_text(encoding='utf-8'))


def save_figure(fig, stem: str, png: bool):
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f'{stem}.pdf', bbox_inches=None, metadata={'Title':stem,'Creator':'TRACER JSA source-grounded figure renderer'})
    if png:
        # 16 x 9 inches * 480 dpi = 7680 x 4320 exact pixels.
        fig.savefig(OUT / f'{stem}_8K.png', dpi=480, bbox_inches=None)
    plt.close(fig)


def figure_7(sweeps, png):
    assert [int(v[0]) for v in sweeps['flood_hz']['rows']] == [40,60,80,100,150,200,300,400]
    assert len(sweeps['vel_jump']['rows']) == 13
    fig, axs = plt.subplots(1, 2, figsize=(16,9), gridspec_kw={'wspace':0.44})
    for ax, name, threshold, title, xlabel in [
        (axs[0],'flood_hz',200,'(a) R1 flooding threshold','Rate threshold (Hz)'),
        (axs[1],'vel_jump',600,'(b) R3 velocity-jump threshold','Velocity step threshold (mm/s)')]:
        rows=sweeps[name]['rows']; x=np.array([r[0] for r in rows]); y=np.array([r[1] for r in rows]); benign=np.array([r[2] for r in rows]);
        assert len(x)>0 and np.max(y)<=100
        line=ax.plot(x,y,'o-',color='#0071bc',linewidth=2.2,markersize=6,label='Attack-event matching')[0]
        ax.set_ylim(-4,110); ax.set_ylabel('Matched events (%)',color=line.get_color()); ax.tick_params(axis='y',labelcolor=line.get_color());
        ax.grid(alpha=0.19); ax.axvline(threshold,linestyle=':',color='#555555',linewidth=1.8)
        ax2=ax.twinx(); line2=ax2.plot(x,benign,'s--',color='#d75f00',markersize=6,linewidth=2,label='Benign alert incidence')[0]
        ax2.set_ylim(0, 21.5 if name=='flood_hz' else 2.55); ax2.set_ylabel('Benign alert incidence (%)', color=line2.get_color()); ax2.tick_params(axis='y',labelcolor=line2.get_color());
        ax.set_title(title,pad=18); ax.set_xlabel(xlabel)
        ax.legend([line,line2],['Attack-event matching','Benign alert incidence'],loc='lower center',fontsize=10,framealpha=0.9)
    fig.text(0.5,.055,'Controlled synthetic traces: 30 scripted events per setting; 9,849 benign frames. Not physical trial rates or field FPR.',ha='center',fontsize=12)
    fig.subplots_adjust(left=.065,right=.92,bottom=.18,top=.88,wspace=.47)
    save_figure(fig,'Fig_7',png)


def figure_8(diag, png):
    windows=[2,4,6,8,12,16,20]; delays=[0.4,2,4,7,9,12,18,25]
    idle=[100,200,300,400,500,700,1000]; pauses=[150,250,350,450,600,800,1100]
    rows6=diag['r6_valid_companion']; rows8=diag['r8_legitimate_resumption']
    assert len(rows6)==56 and len(rows8)==49 and len(diag['r6_missing_companion'])==7
    by6={(int(d['window_us']),int(d['auth_delay_us'])):d for d in rows6}
    by8={(int(d['idle_threshold_ms']),int(d['legitimate_pause_ms'])):d for d in rows8}
    m6=np.array([[int(bool(by6[(w*1000,round(d*1000))]['false_rejection'])) for d in delays] for w in windows]);
    m8=np.array([[int(bool(by8[(w,p)]['burst_false_alert'])) for p in pauses] for w in idle]);
    assert int(m6[3].sum())==4 and int(m8.sum())==28 and int(m8[2].sum())==5
    fig, axs=plt.subplots(1,2,figsize=(16,9),gridspec_kw={'wspace':0.16})
    colors6=ListedColormap(['#daebe7','#f5d8db']); colors8=ListedColormap(['#f1f2f4','#fbe3c5']);
    for ax,m,rows,cols,cmap,title,ylabel,xlabel,default_i,labels in [
        (axs[0],m6,windows,delays,colors6,'(a) R6 valid signed companions','Auth. window (ms)','Companion delay (ms)',3,('A','L')),
        (axs[1],m8,idle,pauses,colors8,'(b) R8 legitimate signed resumptions','Idle threshold (ms)','Legitimate pause (ms)',2,('-','W'))]:
        ax.imshow(m,cmap=cmap,vmin=0,vmax=1,aspect='auto')
        ax.set_xticks(range(len(cols)),[str(v) for v in cols]); ax.set_yticks(range(len(rows)),[str(v) for v in rows]);
        ax.set_xlabel(xlabel,labelpad=14); ax.set_ylabel(ylabel,labelpad=13); ax.set_title(title,pad=20)
        ax.set_xticks(np.arange(-.5,len(cols),1),minor=True); ax.set_yticks(np.arange(-.5,len(rows),1),minor=True)
        ax.grid(which='minor',color='white',linewidth=2); ax.tick_params(which='minor',bottom=False,left=False)
        ax.add_patch(plt.Rectangle((-.48,default_i-.48),len(cols)-.04,.96,fill=False,edgecolor='#b85012',linewidth=3))
        for r in range(len(rows)):
            for c in range(len(cols)):
                ax.text(c,r,labels[m[r,c]],ha='center',va='center',fontsize=16,weight='bold',color='#252525')
    fig.text(.5,.065,'R6: A = valid companion accepted; L = late / NO_AUTH. R8: W = BURST warning; - = no warning.',ha='center',fontsize=12)
    fig.text(.5,.033,'Highlighted rows use configured defaults (8 ms and 300 ms). All cells are synthetic software tests.',ha='center',fontsize=12)
    fig.subplots_adjust(left=.075,right=.972,bottom=.19,top=.86,wspace=.17)
    save_figure(fig,'Fig_8',png)


def figure_9(record, png):
    n=int(record['iterations']); sign=record['sign_us'];
    assert n==200000 and sign['min'] <= sign['median'] <= sign['mean'] <= sign['p99'] <= sign['max']
    values=[sign[k] for k in ('min','median','mean','p99','max')]
    labels=['Minimum','Median','Mean','99th percentile','Maximum']
    fig,ax=plt.subplots(figsize=(16,9)); x=np.arange(5)
    ax.set_yscale('log'); ax.set_ylim(.55,40000)
    bars=ax.bar(x,values,width=.48,color='#2676af',alpha=.84,edgecolor='#164a73',linewidth=1.5)
    ax.axhline(int(record['can_control_period_us']),color='#a64a1a',linestyle='--',linewidth=2,label='Nominal 20 ms control period (20,000 µs)')
    ax.set_xticks(x,labels); ax.set_ylabel('Per-invocation signing time (µs; logarithmic scale)')
    ax.set_title(f'HMAC-SHA-256 signing time on the evaluated Linux host (N = {n:,})',pad=22)
    ax.grid(axis='y',which='both',alpha=.21)
    for b,v in zip(bars,values): ax.text(b.get_x()+b.get_width()/2,v*1.11,f'{v:.3f}',ha='center',fontsize=15)
    ax.legend(loc='upper right',fontsize=12)
    fig.text(.5,.07,'Cryptographic function timing only; the 20 ms reference is not measured end-to-end CAN or embedded latency.',ha='center',fontsize=12)
    fig.subplots_adjust(left=.11,right=.96,bottom=.19,top=.87)
    save_figure(fig,'Fig_9',png)


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check-only',action='store_true',help='Validate preserved numerical inputs without plotting'); ap.add_argument('--no-png',action='store_true'); args=ap.parse_args()
    sweeps=read_json(ROOT/'results'/'sweeps.json')
    diag=read_json(ROOT/'results'/'validated_threshold_diagnostics.json')
    bench=read_json(ROOT/'results'/'today_final_audit'/'hmac_ubuntu_200k.json')
    assert sweeps['flood_hz']['rows'][0]==[40,100.0,17.108]
    assert [r for r in sweeps['vel_jump']['rows'] if r[0]==600][0]==[600,100.0,0.0]
    assert sum(bool(x['burst_false_alert']) for x in diag['r8_legitimate_resumption'])==28
    assert bench['sign_us']['mean']==0.914 and bench['verify_us']['mean']==0.862
    if args.check_only: print('PASS: source-controlled figure input checks'); return
    figure_7(sweeps,not args.no_png);figure_8(diag,not args.no_png);figure_9(bench,not args.no_png)
    print('PASS: generated manuscript figures 7, 8, 9 as PDFs' + ('' if args.no_png else ' and 7680x4320 PNGs'))
if __name__=='__main__':main()
